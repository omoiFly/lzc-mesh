// Shared clipboard on macOS: polls NSPasteboard's change count (there is no
// change notification) and writes content that arrives from other devices.
import AppKit
import ImageIO
import UniformTypeIdentifiers

final class Clipboard: NSObject, URLSessionTaskDelegate {
    weak var hub: Hub?
    weak var files: FilesClient?
    var imageSupported = false
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var lastText: String?
    private var imageTask: URLSessionTask?
    private var imageEpoch = 0
    private var confirming = false
    private let imageWorker = DispatchQueue(label: "lzc-mesh.clipboard-image", qos: .userInitiated)
    static let maxBytes = 256 * 1024
    private static let maxImageBytes = 32 * 1024 * 1024
    private lazy var imageSession: URLSession = {
        let configuration = URLSessionConfiguration.ephemeral
        configuration.connectionProxyDictionary = [:]
        configuration.httpShouldSetCookies = false
        configuration.timeoutIntervalForResource = 120
        return URLSession(configuration: configuration, delegate: self, delegateQueue: .main)
    }()
    // Password managers mark secrets with these types (nspasteboard.org); never forward them.
    private let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    func start() { setActive(AppState.shared.operational) }

    func setActive(_ active: Bool) {
        interruptImage()
        timer?.invalidate(); timer = nil
        lastCount = NSPasteboard.general.changeCount
        lastText = nil
        guard active else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        interruptImage()
        let s = AppState.shared
        guard s.clipboardEnabled, s.operational else { return }
        let types = Set((pb.types ?? []).map { $0.rawValue })
        guard types.isDisjoint(with: skipTypes) else { return }
        let text = pb.string(forType: .string)
        if let text, !text.isEmpty, text != lastText {
            if text.utf8.count <= Clipboard.maxBytes {
                lastText = text
                hub?.send(["t": "clipboard", "text": text])
                s.log("已同步本机剪贴板（\(text.utf8.count) 字节）")
            } else { s.log("剪贴板文本超过 256 KB，未同步") }
        } else if text == nil {
            lastText = nil
        }
        guard imageSupported, !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) else { return }
        let epoch = imageEpoch, count = lastCount
        imageWorker.async { [weak self] in
            guard let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let dimensions = Self.dimensions(source),
                  let png = (Self.isPNG(source) ? data
                             : Self.convert(source, to: .png)) else { return }
            DispatchQueue.main.async {
                guard let self, self.imageCurrent(epoch, count) else { return }
                if png.count > Self.maxImageBytes || !Self.withinImageDimensions(dimensions) {
                    self.confirmFileShare(png, epoch: epoch, count: count)
                } else { self.uploadImage(png, epoch: epoch, count: count) }
            }
        }
    }

    func set(_ text: String, from: String) {
        guard AppState.shared.operational, AppState.shared.clipboardEnabled, !text.isEmpty else { return }
        guard text != lastText else { return }
        interruptImage()
        lastText = text
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastCount = pb.changeCount  // our own write must not be sent back
        AppState.shared.log("已接收来自 \(from.isEmpty ? "其他设备" : from) 的剪贴板（\(text.utf8.count) 字节）")
    }

    func interruptImage() {
        imageEpoch += 1
        imageTask?.cancel()
        imageTask = nil
    }

    private func imageCurrent(_ epoch: Int, _ count: Int) -> Bool {
        imageSupported && imageEpoch == epoch && NSPasteboard.general.changeCount == count
            && AppState.shared.operational && AppState.shared.clipboardEnabled
    }

    private func imageRequest(_ method: String, id: String? = nil) -> URLRequest? {
        let state = AppState.shared
        guard imageSupported, state.operational, state.clipboardEnabled,
              let url = URL(string: "https://lzc-mesh.\(state.boxDomain)/api/clipboard/image\(id.map { "/\($0)" } ?? "")") else { return nil }
        var request = URLRequest(url: url)
        request.httpMethod = method
        request.setValue("Lzc-Auth-Token=\(state.cookie)", forHTTPHeaderField: "Cookie")
        request.setValue(state.deviceID, forHTTPHeaderField: "X-Lzc-Mesh-Device-Id")
        request.setValue(state.fileToken, forHTTPHeaderField: "X-Lzc-Mesh-Device-Token")
        request.setValue("image/png", forHTTPHeaderField: "Content-Type")
        return request
    }

    func urlSession(_ session: URLSession, task: URLSessionTask, willPerformHTTPRedirection response: HTTPURLResponse,
                    newRequest request: URLRequest, completionHandler: @escaping (URLRequest?) -> Void) {
        completionHandler(nil)
    }

    private static func validID(_ id: String) -> Bool {
        id.utf8.count == 43 && id.utf8.allSatisfy {
            (65...90).contains($0) || (97...122).contains($0) || (48...57).contains($0) || $0 == 45 || $0 == 95
        }
    }

    private static func dimensions(_ source: CGImageSource) -> (Int, Int)? {
        guard let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [String: Any],
              let width = properties[kCGImagePropertyPixelWidth as String] as? Int,
              let height = properties[kCGImagePropertyPixelHeight as String] as? Int else { return nil }
        return (width, height)
    }

    private static func withinImageDimensions(_ size: (Int, Int)) -> Bool {
        min(size.0, size.1) > 0 && min(size.0, size.1) <= 4320 && max(size.0, size.1) <= 7680
    }

    private static func isPNG(_ source: CGImageSource) -> Bool {
        guard let type = CGImageSourceGetType(source) else { return false }
        return (type as String) == UTType.png.identifier
    }

    private static func convert(_ source: CGImageSource, to format: UTType) -> Data? {
        guard CGImageSourceGetStatus(source) == .statusComplete,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let data = CFDataCreateMutable(nil, 0),
              let destination = CGImageDestinationCreateWithData(data, format.identifier as CFString, 1, nil) else { return nil }
        let options = format == .tiff ? [kCGImagePropertyTIFFDictionary as String: [kCGImagePropertyTIFFCompression as String: 5]] : [:]
        CGImageDestinationAddImage(destination, image, options as CFDictionary)
        return CGImageDestinationFinalize(destination) ? data as Data : nil
    }

    private func uploadImage(_ png: Data, epoch: Int, count: Int) {
        guard let request = imageRequest("PUT") else { return }
        let task = imageSession.uploadTask(with: request, from: png) { [weak self] data, response, _ in
            guard let self, self.imageCurrent(epoch, count) else { return }
            self.imageTask = nil
            let status = (response as? HTTPURLResponse)?.statusCode ?? 0
            if status == 201, let data, let id = String(data: data, encoding: .utf8), Self.validID(id) {
                self.hub?.send(["t": "clipboard_image", "id": id])
            } else if status == 413 || status == 422 {
                self.confirmFileShare(png, epoch: epoch, count: count)
            } else {
                AppState.shared.log("图片剪贴板上传失败（HTTP \(status)）")
            }
        }
        imageTask = task
        task.resume()
    }

    func receiveImage(_ id: String, size: Int, from: String) {
        guard Self.validID(id), size >= 45, size <= Self.maxImageBytes,
              let request = imageRequest("GET", id: id) else { return }
        let count = NSPasteboard.general.changeCount
        if count != lastCount {
            // Preserve a local copy that arrived before the next timer tick.
            poll()
            return
        }
        interruptImage()
        let epoch = imageEpoch
        let task = imageSession.downloadTask(with: request) { [weak self] file, response, _ in
            guard let self, self.imageCurrent(epoch, count) else { return }
            self.imageTask = nil
            guard let file, (response as? HTTPURLResponse)?.statusCode == 200,
                  (try? file.resourceValues(forKeys: [.fileSizeKey]).fileSize) == size,
                  let png = try? Data(contentsOf: file, options: .mappedIfSafe) else {
                AppState.shared.log("图片剪贴板下载失败")
                return
            }
            self.imageWorker.async { [weak self] in
                guard let source = CGImageSourceCreateWithData(png as CFData, nil),
                      Self.isPNG(source),
                      let dimensions = Self.dimensions(source), Self.withinImageDimensions(dimensions),
                      let tiff = Self.convert(source, to: .tiff) else { return }
                DispatchQueue.main.async {
                    guard let self, self.imageCurrent(epoch, count) else { return }
                    let item = NSPasteboardItem()
                    guard item.setData(png, forType: .png), item.setData(tiff, forType: .tiff) else { return }
                    let pasteboard = NSPasteboard.general
                    pasteboard.clearContents()
                    if pasteboard.writeObjects([item]) {
                        self.lastText = nil
                        AppState.shared.log("已接收来自 \(from.isEmpty ? "其他设备" : from) 的剪贴板图片")
                    }
                    self.lastCount = pasteboard.changeCount
                }
            }
        }
        imageTask = task
        task.resume()
    }

    private func confirmFileShare(_ png: Data, epoch: Int, count: Int) {
        guard !confirming else { return }
        confirming = true
        let alert = NSAlert()
        alert.messageText = "图片超出同步限制"
        alert.informativeText = "图片剪贴板支持最高 8K、最大 32 MiB。可以将原分辨率图片上传到文件共享，由其他设备下载。"
        alert.addButton(withTitle: "通过文件共享发送")
        alert.addButton(withTitle: "取消")
        let result = alert.runModal()
        confirming = false
        guard result == .alertFirstButtonReturn, imageCurrent(epoch, count) else { return }
        files?.uploadClipboardPNG(png)
    }
}
